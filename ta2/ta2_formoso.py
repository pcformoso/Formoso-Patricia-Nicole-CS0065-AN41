# dictionary
rooms = {
    "A": "clean",
    "B": "clean"
}

# check state
def is_dirty(room_state):
    if room_state == "dirty":
        return True
    else:
        return False

def clean_room(room_name):
    rooms[room_name] = "clean"

# rule-based agent class
class VacuumAgent:
    def __init__(self, start_location):
        self.location = start_location

    def move(self):

        if self.location == "A":
            self.location = "B"
        else:
            self.location = "A"

    def perceive_and_act(self):
        current_state = rooms[self.location]

        # Rule 1: if dirty, clean
        if is_dirty(current_state):
            clean_room(self.location)
            return "cleaned"

        # Rule 2: if clean, move
        else:
            self.move()
            return "moved"


print("Set the initial states of the rooms (type 'dirty' or 'clean').")
rooms["A"] = input("Room A state: ").lower()
rooms["B"] = input("Room B state: ").lower()

steps = int(input("How many steps should the simulation run? "))

# start at A
agent = VacuumAgent("A")

print("\n--- Simulation Start ---")
for i in range(steps):
    print(f"\nStep {i + 1}:")
    print(f"Location: Room {agent.location}")

    action = agent.perceive_and_act()

    print(f"Action taken: {action}")
    print(f"Current Environment: {rooms}")