# PART 1 - Knowledge Representation

knowledge_base = {
    "facts": {
        "wont_turn_on": True,
        "beep_codes": 3,
        "screen_is_black": True,
        "is_plugged_in": True,
        "spilled_water": False
    },

    "categories": {
        "status": ["wont_turn_on"],
        "error": ["beep_codes"],
        "display": ["screen_is_black"],
        "power": ["is_plugged_in"],
        "damage": ["spilled_water"]
    }
}

facts = knowledge_base["facts"]

print("INPUT - Knowledge Base")
print("Facts:", facts)
print("Categories:", list(knowledge_base["categories"].keys()))


# PART 2 - Rule-Based Reasoning

def rule_power(facts):
    if facts["wont_turn_on"] and not facts["is_plugged_in"]:
        return "Plug in the power cable."
    return None


def rule_ram(facts):
    if facts["beep_codes"] == 3:
        return "Reseat the RAM sticks."
    return None


def rule_screen(facts):
    if facts["screen_is_black"] and facts["is_plugged_in"]:
        return "Check the monitor display cable."
    return None


rules = [rule_power, rule_ram, rule_screen]


def inference_engine(current_facts):
    actions = []

    print("\nPROCESS - Checking the rules")

    for rule in rules:
        result = rule(current_facts)
        print("Checking", rule.__name__)

        if result:
            print("Action found:", result)
            actions.append(result)
        else:
            print("No action from this rule.")

    return actions


rbr_actions = inference_engine(facts)

print("\nOUTPUT - Rule-Based Reasoning Actions")
for action in rbr_actions:
    print("-", action)


# PART 3 - Case-Based Reasoning

case_base = [
    {
        "problem": {
            "wont_turn_on": True,
            "beep_codes": 0
        },
        "solution": "Check the power cable."
    },
    {
        "problem": {
            "wont_turn_on": True,
            "beep_codes": 3
        },
        "solution": "Reseat the RAM sticks."
    },
    {
        "problem": {
            "screen_is_black": True,
            "beep_codes": 1
        },
        "solution": "Replace the monitor."
    }
]

new_problem = {
    "wont_turn_on": True,
    "beep_codes": 3,
    "screen_is_black": True
}

print("\nINPUT - New Problem")
print(new_problem)


# Retrieve step
def get_similarity(past_problem, current_problem):
    score = 0

    for key in current_problem:
        if key in past_problem:
            if past_problem[key] == current_problem[key]:
                score += 1

    return score


print("\nPROCESS - Comparing the new problem with past cases")

best_match = None
highest_score = -1

for case in case_base:
    score = get_similarity(case["problem"], new_problem)
    print("Similarity score:", score)

    if score > highest_score:
        highest_score = score
        best_match = case


# Reuse step
final_solution = best_match["solution"]

print("\nREUSE - Retrieved Solution")
print(final_solution)


# Revise step
user_feedback = input("\nDid this solution work? Type yes or no: ").strip().lower()

if user_feedback == "no":
    final_solution = input("Enter the revised solution: ").strip()
    print("Revised solution:", final_solution)
else:
    print("The retrieved solution was kept.")


# Retain step
case_base.append({
    "problem": new_problem.copy(),
    "solution": final_solution
})

print("\nRETAIN - New case added to the case base.")
print("New Case Base length:", len(case_base))